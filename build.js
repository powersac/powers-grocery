#!/usr/bin/env node
// Assemble the page and the Worker. Everything is inlined: one HTML string in
// one JS file, so deploying is a single wrangler command with no asset step.
'use strict';
const fs = require('fs');
const path = require('path');
const here = f => path.join(__dirname, f);

function die(m) { console.error('build failed: ' + m); process.exit(1); }

const style = fs.readFileSync(here('src/style.css'), 'utf8');
const body  = fs.readFileSync(here('src/page.body.html'), 'utf8');
const app   = fs.readFileSync(here('src/app.js'), 'utf8');
const ops   = fs.readFileSync(here('src/ops.js'), 'utf8');
const api   = fs.readFileSync(here('src/api.js'), 'utf8');
const cron  = fs.readFileSync(here('src/cron.js'), 'utf8');

const PAGE = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="robots" content="noindex, nofollow">
<meta name="referrer" content="no-referrer">
<meta name="theme-color" content="#35603F">
<title>Groceries</title>
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'%3E%3Ctext y='.9em' font-size='90'%3E%F0%9F%9B%92%3C/text%3E%3C/svg%3E">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" media="print" onload="this.media='all'"
      href="https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,600&family=Karla:wght@400;500;600;700&display=swap">
${style}
</head>
<body>
${body}
<script>
${app}
</script>
</body>
</html>
`;

// Sanity, before it can ever reach a phone.
if (!/<!doctype html>/.test(PAGE)) die('the page lost its doctype');
if (PAGE.indexOf('</script>\n</body>') === -1) die('the page script is not closed properly');
try { new Function(app); } catch (e) { die('app.js has a syntax error: ' + e.message); }
for (const id of ['rows', 'tally', 'when', 'dl', 'addform', 'add-name', 'f-buy', 'f-all', 'q',
                  'banner', 'picker', 'picker-opts', 'toast', 'dinners', 'footnote', 'refresh']) {
  if (!new RegExp('id="' + id + '"').test(PAGE)) die('the page is missing #' + id + ', which the script uses');
}
// Every $("x") the script reaches for must exist in the markup.
const wanted = [...app.matchAll(/\$\("([a-z-]+)"\)/g)].map(m => m[1]);
const missing = [...new Set(wanted)].filter(id => !new RegExp('id="' + id + '"').test(PAGE));
if (missing.length) die('the script looks for ids the page does not have: ' + missing.join(', '));

const strip = src => src
  .replace(/^'use strict';\n/m, '')
  .replace(/\nmodule\.exports = \{[\s\S]*?\};\n?/, '\n')
  // Bundled together, ops' functions are already in scope. Every file that
  // requires ops drops its require line; the namespace is declared once, in the
  // template below. Declaring it per file would redeclare O and fail to parse.
  .replace(/^const O = require\('\.\/ops\.js'\);\n/m, '');


const WORKER = `// Powers grocery list. Built by build.js from src/ - do not edit this file.
// Deploy:  npx wrangler deploy
'use strict';

const PAGE_HTML = ${JSON.stringify(PAGE)};

/* ---------- list logic ---------- */
${strip(ops)}

// ops' functions are in scope above; O is the namespace the other files use.
const O = { AISLES, WINDOW_MIN, WINDOW_MAX, norm, sameName, guessAisle, today, sortItems, find, apply, rollWindow, validate };

/* ---------- request handling ---------- */
${strip(api)}

/* ---------- keeping the window full on a schedule ---------- */
${strip(cron)}

/* ---------- storage: one KV key, with a revision for safe concurrent writes ---------- */

const KEY = 'state';
function makeStore(env) {
  return {
    async get() {
      const raw = await env.LIST.get(KEY);
      if (!raw) return { rev: 0, data: seedState() };
      try {
        const o = JSON.parse(raw);
        if (!o || typeof o.rev !== 'number' || !o.data) throw new Error('shape');
        return o;
      } catch (e) {
        // Never hand a corrupt blob to the page. An empty list is recoverable;
        // a page that will not render is not.
        return { rev: -1, data: seedState(), corrupt: true };
      }
    },
    async put(data, expectedRev) {
      const cur = await this.get();
      if (cur.rev !== expectedRev) return false;
      await env.LIST.put(KEY, JSON.stringify({ rev: cur.rev + 1, data }));
      return true;
    }
  };
}
function seedState() {
  return { built: today(), aisles: AISLES, items: [], dinners: [] };
}

export default {
  // Cloudflare's cron. No token, no HTTP, no laptop: this runs inside the
  // Worker against its own KV, so it cannot be blocked by an egress proxy.
  // It only ever fills empty days. Nights they set are never touched.
  async scheduled(event, env, ctx) {
    const store = makeStore(env);
    const now = today();
    const cur = await store.get();
    if (cur.corrupt) return;              // never write on top of a blob we could not parse
    const r = topUp(cur.data, now);
    if (!r.added.length) return;          // window already full, nothing to do
    if (validate(r.state).length) return; // never store a state the page cannot render
    // Compare-and-set. A false return means a phone wrote first; that is fine,
    // tomorrow's run sees the newer state. Never retry blind.
    await store.put(r.state, cur.rev);
  },

  async fetch(request, env) {
    const bound = Object.assign({}, env, { PAGE_HTML });
    try {
      const r = await handle(request, bound, makeStore(env), today());
      return new Response(r.body, { status: r.status || 200, headers: r.headers || {} });
    } catch (e) {
      return new Response(JSON.stringify({ error: 'server_error' }), {
        status: 500, headers: { 'content-type': 'application/json' } });
    }
  }
};
`;

if (/\brequire\(/.test(WORKER)) die('the bundle still has a require() in it');
if (/module\.exports/.test(WORKER)) die('the bundle still has a module.exports in it');
try { new Function('export_placeholder', WORKER.replace(/^export default \{[\s\S]*$/m, '')); }
catch (e) { die('the bundle has a syntax error: ' + e.message); }

fs.writeFileSync(here('worker.js'), WORKER);
fs.writeFileSync(here('page.preview.html'), PAGE);
console.log(`built worker.js (${WORKER.length}B) and page.preview.html (${PAGE.length}B)`);
